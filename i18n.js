let lang = 'ru';

export function setLang(l) {
    lang = dict[l] ? l : 'ru';
}

export function getLang() {
    return lang;
}

export function t(key, params = {}) {
    let v = dict[lang][key] ?? dict.ru[key] ?? key;
    if (typeof v === 'object') {
        const form = new Intl.PluralRules(lang).select(params.n ?? 0);
        v = v[form] ?? v.other;
    }
    return v.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? `{${k}}`));
}

